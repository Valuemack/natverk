const KALLA = "https://www.un.org/en/observances/list-days-weeks";
const html = await hamta(KALLA);
const rader = html.split(/<div class="views-row/).slice(1).map((r) => {
  const a = r.match(/<a [^>]*href="([^"]+)"[^>]*>([^<]+)<\/a>/);
  const d = r.match(/content="\d{4}-(\d\d-\d\d)/);
  return a && d ? { mmdd: d[1], titel: text(a[2]).trim().replace(/&#0?39;/g, "'"), url: a[1] } : null;
}).filter(Boolean);
const fel = [];
const dagar = {};
for (const [mmdd, titel, sv] of DAGAR) {
  const r = rader.find((x) => x.titel === titel);
  if (!r) { fel.push(`saknas i FN-listan: ${titel}`); continue; }
  if (r.mmdd !== mmdd) { fel.push(`fel datum: ${titel} (${mmdd}, FN: ${r.mmdd})`); continue; }
  (dagar[mmdd] ??= []).push({ sv, en: titel.replace(/\s*\[[^\]]+\]$/, ""), url: r.url.replace(/^http:/, "https:") });
}
if (fel.length) { console.error(fel.join("\n")); process.exit(1); }
skrivJson("fn-dagar.json", {
  kalla: "Förenta nationerna, List of International Days and Weeks",
  url: KALLA,
  hamtad: new Date().toISOString().slice(0, 10),
  not: "Bara dagar med fast datum. Svensk benämning är redaktionens översättning där etablerat svenskt namn saknas.",
  dagar,
});
