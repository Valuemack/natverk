// Skriver data/LICENS-OCH-KALLOR.txt från sources.mjs + hämtstatus + rapport (så filen alltid stämmer med datat).
import fs from 'node:fs';
import path from 'node:path';
import { DATA_DIR, RAW_DIR, readJson } from './lib.mjs';
import { LEK, PARK, ARCGIS } from './sources.mjs';

const st = readJson(path.join(RAW_DIR, 'kommun-status.json'), {});
const ops = readJson(path.join(RAW_DIR, 'operatorer-status.json'), {});
const rap = readJson(path.join(DATA_DIR, 'rapport.json'), {});
const L = [];
const line = (s = '') => L.push(s);
const row = (tema, s) => {
  const k = st[`${tema}-${s.id}`] || {};
  const status = k.ok ? `${k.antal} objekt` : k.blockerad ? `BLOCKERAD: ${k.fel}` : k.fel ? `ej hämtad: ${k.fel}` : 'ej körd';
  line(`- [${tema}] ${s.id} (${s.kommun}${s.roll ? `, används som ${s.roll}` : ''})`);
  line(`    Licens: ${s.licens}${s.not ? ` – ${s.not}` : ''}`);
  line(`    Källa:  ${s.url}`);
  line(`    Status: ${status}`);
};

line('LICENS OCH KÄLLOR – parkeringar.json och lekplatser.json');
line(`Genererad: ${new Date().toISOString().slice(0, 10)} av scripts/20-licens.mjs`);
line('='.repeat(78));
line();
line('PRINCIPER FÖR INSAMLINGEN');
line('- Endast fakta (läge, namn, adress, antal platser, taxa, öppettider, utrustning). Fritext (beskrivningar)');
line('  tas bara med när källans licens tillåter återanvändning (CC0 / CC BY). Operatörernas texter tas aldrig med.');
line('- robots.txt kontrolleras för varje URL (grupperna "*" samt AI-/dataset-specifika user-agents, t.ex.');
line('  ClaudeBot, anthropic-ai, GPTBot, CCBot, Google-Extended). Disallow och Crawl-delay respekteras.');
line('- Max 1 anrop per sekund och värd, generisk User-Agent "dataset-builder/1.0 (open data compilation)".');
line('- Ingen inloggning, ingen registrering, inga API-nycklar, ingen CAPTCHA/botskydd kringgås.');
line('  Tjänster som kräver nyckel/inloggning har hoppats över (se BLOCKERAT nedan).');
line();
line('GRUNDDATA: OPENSTREETMAP (ODbL 1.0)');
line('- Basdataseten kommer från ../osm-data/data (OpenStreetMap via Overpass/Geofabrik).');
line('- © OpenStreetMap-bidragsgivare, Open Database License 1.0, https://www.openstreetmap.org/copyright');
line('- Sammanslagningen med OSM gör filerna till en härledd databas enligt ODbL: visa attributionen på varje');
line('  sida, och om själva databasen (JSON-filerna) delas ut publikt måste den delas under ODbL.');
line('  Webbsidor som bara visar datat räknas som "Produced Work" och kräver attribution.');
line();
line('ATTRIBUTIONSKRAV (visa på sidor som använder respektive kommuns data)');
line('- CC BY: Uppsala kommun, Luleå kommun ("Geodataproducent: Luleå kommun"), Jönköpings kommun,');
line('  Växjö kommun, Skellefteå kommun (CC BY 4.0), Helsingborgs stad (CC BY 4.0, parkering).');
line('- CC0: ingen attribution krävs, men källan anges ändå i fältet "kallor" per objekt.');
line('- "ej angiven": kommunen har publicerat datat som öppna data utan att ange licens. Endast fakta används,');
line('  ingen fritext. Kontakta kommunen om en uttrycklig licens behövs.');
line();
line('KOMMUNALA ÖPPNA DATA – LEKPLATSER');
for (const s of LEK) row('lek', s);
for (const s of ARCGIS.filter((x) => x.tema === 'lek')) row('lek', s);
line();
line('KOMMUNALA ÖPPNA DATA – PARKERING');
for (const s of PARK) row('park', s);
for (const s of ARCGIS.filter((x) => x.tema === 'park')) row('park', s);
line();
line('OPERATÖRER (publika anläggningssidor, hittade via operatörens egen sitemap.xml)');
line('Ingen öppen licens. Endast faktauppgifter extraheras. OBS – databasrätt: i EU/Sverige kan en');
line('operatörs samlade anläggningsregister skyddas som databas/katalog (URL 49 §) när en väsentlig del');
line('återges. Bedöm själv om operatörsdatat ska publiceras; det kan stängas av helt med');
line('UTAN_OPERATORER=1 node scripts/10-build.mjs (posterna markeras med operatören i "kallor").');
for (const [k, s] of Object.entries(ops)) line(`- ${s.operator}: ${s.poster ?? 0} sidor tolkade (${s.sidor ?? 0} hämtade, ${s.cache ?? 0} från cache, ${s.fel ?? 0} fel [HTTP 404 m.m. för inaktuella sitemap-poster], ${s.blockerade ?? 0} blockerade)${s.avbrutet ? ` – ${s.avbrutet}` : ''}`);
line();
line('BLOCKERAT / EJ ANVÄNT');
line('- Stockholms stad, LTF-Tolken: ANVÄNDS (ingen nyckel krävs för ptillaten/all). Det är gatuparkerings-');
line('  föreskrifter (linjer), inte anläggningar, så det används bara som "taxezon_kommun" för parkeringar inom');
line('  35 m från en avgiftsbelagd gatusträcka. Övriga API:er på Stockholms öppna data-portal kräver nyckel.');
line('- Stockholms stad, "Hitta service"-API (lekplatser): kräver API-nyckel (registrering) och svarade');
line('  inte (timeout). Ingen Stockholmsdata för lekplatser.');
line('- Göteborgs Stad, ParkingService v2.3 (data.goteborg.se, CC0): kräver APPID (gratis registrering).');
line('  Inte registrerat enligt instruktion. Göteborgs lekplatser finns inte som öppen datamängd.');
line('- Stockholm Parkering /api/map: "Authorization has been denied" – inte använd (anläggningssidorna används).');
line('- Swedavia: priser hämtas dynamiskt via bokningsmotor med token. Inte hämtat. Flygplatsparkeringar');
line('  identifieras i stället geografiskt (OSM-objekt nära flygplatsen) och länkas till Swedavias parkeringssida.');
line('- Umeå kommun (opendata.umea.se, Opendatasoft): robots.txt har "Disallow: /api/" och');
line('  "Disallow: /explore/dataset/*/download" för alla user-agents – lekplatsdatat (CC0) hämtas därför inte.');
line('- Helsingborgs stad, lekplatser: CC BY-NC 4.0 (icke-kommersiell) – utesluten (sajterna är kommersiella).');
line('- EasyPark: robots.txt "Disallow: /api/", ingen publik zonlista – inte använd.');
line('- Q-Park (q-park.se), Falun (falun.entryscape.net), Trelleborg (catalog.trelleborg.se): DNS-uppslag (även vid omförsök)');
line('  misslyckades från körmiljön. Region Gotland: tidsgräns. Försök igen med node scripts/run-all.mjs.');
line('- Uppsala kommuns egen portal (opendata.uppsala.se, ArcGIS Hub, Crawl-delay 60): lekplatserna hämtas via');
line('  Esri Sveriges publicering av samma data (CC BY, 2015).');
line('- Trafikverkets API (rastplatser/parkering): kräver API-nyckel – inte använd.');
line();
line('STATISTIK (från data/rapport.json)');
const lp = rap.lekplatser || {}, pp = rap.parkeringar || {};
line(`- Lekplatser: ${lp.antal} totalt, ${lp.matchade_osm_officiell} OSM-objekt berikade med officiell data, ${lp.nya_officiella} nya officiella objekt.`);
line(`- Parkeringar: ${pp.antal} totalt, ${pp.osm_berikade_med_officiell} OSM-objekt berikade, ${pp.nya_officiella} nya officiella/operatörsobjekt.`);
fs.writeFileSync(path.join(DATA_DIR, 'LICENS-OCH-KALLOR.txt'), L.join('\n') + '\n');
console.log('Skrev data/LICENS-OCH-KALLOR.txt');
